module Buildr.Plan
  ( -- * Pure Parser
    parsePlanJson
    -- * File Loader
  , defaultPlanPath
  , loadPlanJson
  ) where

import Buildr.Error (PlanError (..))
import Buildr.Event (PlanUnit (..), UnitStyle (..))
import Data.Aeson (FromJSON (..), (.:), (.:?), withObject, eitherDecodeStrict)
import qualified Data.ByteString as BS
import Data.Text (Text)
import qualified Data.Text as T
import GHC.Generics (Generic)
import System.Directory (doesFileExist)

-- | Intermediate representation for raw units inside plan.json's 'install-plan'.
data RawInstallUnit = RawInstallUnit
  { rawUnitId        :: !Text
  , rawUnitPkg       :: !Text
  , rawUnitVer       :: !Text
  , rawUnitComp      :: !(Maybe Text)
  , rawUnitStyle     :: !(Maybe Text)
  , rawUnitDepends   :: ![Text]
  } deriving (Eq, Show, Generic)

instance FromJSON RawInstallUnit where
  parseJSON = withObject "RawInstallUnit" $ \o -> RawInstallUnit
    <$> o .: "id"
    <*> o .: "pkg-name"
    <*> o .: "pkg-version"
    <*> o .:? "component-name"
    <*> o .:? "style"
    <*> o .: "depends"

-- | Top-level schema wrapper for plan.json.
newtype RawPlan = RawPlan
  { rawPlanUnits :: [RawInstallUnit]
  } deriving (Eq, Show, Generic)

instance FromJSON RawPlan where
  parseJSON = withObject "RawPlan" $ \o -> RawPlan
    <$> o .: "install-plan"

-- | Default location of plan.json generated by Cabal build --dry-run.
defaultPlanPath :: FilePath
defaultPlanPath = "dist-newstyle/cache/plan.json"

-- | Purely parses the ByteString content of plan.json into validated 'PlanUnit' records.
parsePlanJson :: BS.ByteString -> Either PlanError [PlanUnit]
parsePlanJson bytes = case eitherDecodeStrict bytes of
  Left err -> Left (PlanJsonParseFailure "plan.json" (T.pack err))
  Right (RawPlan rawUnits) -> Right (map translateUnit rawUnits)

-- | Purely translates a raw plan JSON unit into the domain 'PlanUnit'.
translateUnit :: RawInstallUnit -> PlanUnit
translateUnit raw =
  let style = case rawUnitStyle raw of
        Just "local" -> StyleLocal
        _            -> StyleStore
      component = case rawUnitComp raw of
        Just comp -> comp
        Nothing   -> "lib"
  in PlanUnit
       { puId            = rawUnitId raw
       , puPackage       = rawUnitPkg raw
       , puVersion       = rawUnitVer raw
       , puComponent     = component
       , puStyle         = style
       , puDependencies  = rawUnitDepends raw
       , puRebuildReason = Nothing
       }

-- | Loads and parses plan.json from disk, returning 'PlanJsonNotFound' if missing.
loadPlanJson :: FilePath -> IO (Either PlanError [PlanUnit])
loadPlanJson path = do
  exists <- doesFileExist path
  if not exists
    then pure (Left (PlanJsonNotFound path))
    else do
      content <- BS.readFile path
      case eitherDecodeStrict content of
        Left err -> pure (Left (PlanJsonParseFailure path (T.pack err)))
        Right (RawPlan rawUnits) -> pure (Right (map translateUnit rawUnits))
